import statistics as st
data = [4,8,5,2,88,2,9,7]
print("Mean is : ", st.mean(data))
print("Median is : ",st.median(data))
print("Mode is : ",st.mode(data))
print("Standard deviation is : ", st.stdev(data))
print("High median is : ", st.median_high(data))
print("Low median is : ", st.median_low(data))